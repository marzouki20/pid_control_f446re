/* USER CODE BEGIN Header */
#include "main.h"
#include "motor.h"
#include "encoder.h"
#include <stdio.h>
#include <string.h>
/* USER CODE END Header */

// Déclaration des timers
TIM_HandleTypeDef htim1; // PWM Moteur Gauche
TIM_HandleTypeDef htim3; // PWM Moteur Droit
TIM_HandleTypeDef htim2; // Encodeur Gauche
TIM_HandleTypeDef htim4; // Encodeur Droit
UART_HandleTypeDef huart2;

void SystemClock_Config(void);
static void MX_GPIO_Init(void);
static void MX_USART2_UART_Init(void);
static void MX_TIM1_Init(void);
static void MX_TIM3_Init(void);
static void MX_TIM2_Init(void);
static void MX_TIM4_Init(void);

int main(void)
{
  HAL_Init();
  SystemClock_Config();
  MX_GPIO_Init();
  MX_USART2_UART_Init();
  MX_TIM1_Init();
  MX_TIM3_Init();
  MX_TIM2_Init();
  MX_TIM4_Init();

  /* USER CODE BEGIN 2 */
  char printMessage[60] = {'\0'};

  // Initialisation du matériel
  Motor_Init();
  Encoder_Init();

  HAL_Delay(1000); // Petite pause avant de démarrer
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */

    // ==========================================
    // 1. FAIRE TOURNER LES MOTEURS (1 SECONDE)
    // ==========================================
    Motor_SetSpeed_Gauche(520);
    Motor_SetSpeed_Droite(500);

    HAL_Delay(1000); // Tourne pendant 1 seconde

    // ==========================================
    // 2. ARRÊTER LES MOTEURS DÉFINITIVEMENT
    // ==========================================
    Motor_Stop();

    // On lit les compteurs une dernière fois pour voir où on s'est arrêté
    int32_t countG = Encoder_GetCount_Gauche();
    int32_t countD = Encoder_GetCount_Droite();

    sprintf(printMessage, "Arrêt ! Gauche: %ld | Droite: %ld\r\n", countG, countD);
    HAL_UART_Transmit(&huart2, (uint8_t*)printMessage, strlen(printMessage), 100);

    // ==========================================
    // 3. BOUCLE INFINIE (Le moteur ne redémarre plus)
    // ==========================================
    while (1) {
        HAL_Delay(1000); // On ne fait plus rien, on attend.
    }
  }
  /* USER CODE END 3 */
}

