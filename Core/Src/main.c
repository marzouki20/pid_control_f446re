/* USER CODE BEGIN Header */
#include "main.h"
#include "motor.h"
#include "encoder.h"
#include "pid.h"
#include <stdio.h>
#include <string.h>
#include <math.h> // For the target ramp
/* USER CODE END Header */

TIM_HandleTypeDef htim1;
TIM_HandleTypeDef htim3;
UART_HandleTypeDef huart2;

void SystemClock_Config(void);
static void MX_GPIO_Init(void);
static void MX_USART2_UART_Init(void);
static void MX_TIM1_Init(void);
static void MX_TIM3_Init(void);

int main(void)
{
  HAL_Init();
  SystemClock_Config();
  MX_GPIO_Init();
  MX_USART2_UART_Init();
  MX_TIM1_Init();
  MX_TIM3_Init();

  /* USER CODE BEGIN 2 */
  char printMessage[50] = {'\0'};

  // ==========================================
  // 1. PID SETUP (Position Control)
  // ==========================================
  PID_Controller posPID;

  // Kp = 0.5f, Ki = 0.01f, Kd = 0.1f
  // Output limits: 100% (forward), -100% (backward)
  PID_Init(&posPID, 0.01f, 0.00f, 0.0f, 100.0f, -100.0f);

  float final_target = 6000.0f; // The exact count you want to reach
  float current_target = 0.0f;  // The ramped target for smooth movement

  Motor_Init();
  Encoder_Init();

  uint32_t last_pid_tick = 0;
  uint32_t last_print_tick = 0;

  HAL_Delay(1000); // Wait for stabilization
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */

    // Run PID every 10ms
    if (HAL_GetTick() - last_pid_tick >= 10)
    {
        float dt = (HAL_GetTick() - last_pid_tick) / 1000.0f;
        last_pid_tick = HAL_GetTick();

        // 1. Ramp the target slowly (so the motor doesn't jerk to 100% instantly)
        if (current_target < final_target) {
            current_target += 10.0f; // Increase target by 10 counts every 10ms
            if (current_target > final_target) current_target = final_target;
        }

        // 2. Read the Encoder (Actual Position)
        float current_position = (float)Encoder_GetCount();

        // 3. Compute PID
        float pid_output = PID_Compute(&posPID, current_target, current_position, dt);

        // 4. Apply to Motor
        Motor_SetSpeed(pid_output);

        // 5. Print to PuTTY (Every 50ms)
        if (HAL_GetTick() - last_print_tick >= 50) {
            last_print_tick = HAL_GetTick();

            // Print: Target Count, Actual Count, PID Output
            sprintf(printMessage, "%d,%d,%d\r\n",
                    (int)current_target, (int)current_position, (int)pid_output);
            HAL_UART_Transmit(&huart2, (uint8_t*)printMessage, strlen(printMessage), 100);
        }
    }
  }
  /* USER CODE END 3 */
}

